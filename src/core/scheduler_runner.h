// Ядро (lib/schedule) ничего не знает про Arduino и время: сюда сходятся
// NTP, часовой пояс, координаты и применение результата к состоянию ленты.
#pragma once

#include <Arduino.h>

namespace lumen {

void schedulerBegin();

// Вызывать примерно раз в секунду.
void schedulerTick(uint32_t nowMs);

// Есть ли синхронизированное время. Пока времени нет, планировщик
// намеренно ничего не делает: дёргать ленту по неизвестным часам хуже,
// чем не делать ничего.
bool timeIsValid();

// Диагностика для интерфейса: время, часовой пояс, солнце, активное правило.
String schedulerStatusJson();

}  // namespace lumen
